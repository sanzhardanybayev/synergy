import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { dim, green } from 'kleur/colors';
import { resolveProjectPaths } from './paths.js';
import { generateSessionName, uniqueSessionName } from './session-name.js';

export type SpecType = 'feature' | 'refactor' | 'project';

const VALID_TYPES: SpecType[] = ['feature', 'refactor', 'project'];

export function isSpecType(t: string): t is SpecType {
  return (VALID_TYPES as string[]).includes(t);
}

interface SpecOptions {
  title: string;
  type: SpecType;
  /** Explicit session name override. Skips auto-generation. */
  sessionName?: string;
  root?: string;
  now?: Date;
}

export interface SpecResult {
  sessionDir: string;
  sessionName: string;
  files: string[];
}

