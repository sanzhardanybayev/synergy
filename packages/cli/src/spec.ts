const ORCHESTRATOR_TEMPLATE = (title: string, type: SpecType, sessionName: string) => `# Orchestrator — ${title}

> **Read this first** before implementing any of the specs in this session.
> Session: \`${sessionName}\`. Type: \`${type}\`.

## Overview

_One paragraph: what is being built, why, and what the success criteria are._

## Dependency graph

Implementation order — items on the same line can run in parallel.

\`\`\`
Phase 1 (foundation)
  └─> Phase 2 (core) ┐
                     ├─> Phase 3 (polish)
  └─> Phase ?  ──────┘
\`\`\`

## Parallel chunks

- **Sequential gate:** Phase 1 must land first; nothing else may start.
- **Parallelizable:** _List the phases or chunks that can run as parallel sub-agents._

## Agent strategy

- **Use sub-agents (single-shot, isolated work)** for: file-bounded implementation tasks where the interface is already specified.
- **Use an agent team (multi-step, exploratory)** for: cross-cutting concerns, debugging, integration testing.
- **Keep human in the loop** at every phase boundary: present a diff, run tests, get approval.

## Verification gates

- After Phase 1: \`pnpm build\` clean, types resolve.
- After Phase 2: feature works end-to-end against a smoke test.
- After Phase 3: docs + examples shipped, CI green.

## How to invoke

Reference this session in Claude Code with:

\`\`\`
Implement the plan in @.synergy/sessions/${sessionName}/
Start with orchestrator.md, then walk the specs in order.
\`\`\`
`;

export function createSpec(opts: SpecOptions): SpecResult {
  const paths = resolveProjectPaths(opts.root);
  mkdirSync(paths.sessionsDir, { recursive: true });

  const baseName = opts.sessionName ?? generateSessionName(opts.title, opts.now);
  const sessionName = uniqueSessionName(paths.sessionsDir, baseName, opts.title);
  const sessionDir = join(paths.sessionsDir, sessionName);
  mkdirSync(sessionDir, { recursive: true });
  mkdirSync(join(sessionDir, '_components'), { recursive: true });
  mkdirSync(join(sessionDir, 'assets'), { recursive: true });

  const files: Array<{ name: string; body: string }> = [
    { name: '00-overview.mdx', body: OVERVIEW_TEMPLATE(opts.title, opts.type) },
    { name: '01-architecture.mdx', body: ARCHITECTURE_TEMPLATE(opts.title) },
    { name: '02-implementation.mdx', body: IMPLEMENTATION_TEMPLATE(opts.title) },
    { name: 'orchestrator.md', body: ORCHESTRATOR_TEMPLATE(opts.title, opts.type, sessionName) },
  ];

  const written: string[] = [];
  for (const f of files) {
    const path = join(sessionDir, f.name);
    writeFileSync(path, f.body);
    written.push(path);
  }

  process.stdout.write(green('✓') + ` Created session ` + dim(sessionName) + `\n`);
  for (const path of written) {
    process.stdout.write('  ' + dim(path.replace(`${paths.root}/`, '')) + '\n');
  }
  return { sessionDir, sessionName, files: written };
}
